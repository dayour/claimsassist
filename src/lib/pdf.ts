// Generates a one-page PDF summary of a claim using jsPDF and returns the
// content as raw base64 (no data: prefix), ready for Dataverse annotations
// via Dataverse custom action payloads and annotation attachments.

import { jsPDF } from "jspdf";
import type { Claim } from "../data/seed";

const NAVY = "#1f3864";
const BLUE = "#2e75b6";
const GREY = "#595959";

function money(n: number): string {
  return "$" + (n ?? 0).toLocaleString("en-US");
}

export interface ClaimPdf {
  base64: string;
  bytes: Uint8Array;
  fileName: string;
}

export function generateClaimPdf(c: Claim): ClaimPdf {
  const doc = new jsPDF({ unit: "pt", format: "letter" });
  const left = 54;
  let y = 60;

  doc.setFillColor(NAVY);
  doc.rect(0, 0, 612, 90, "F");
  doc.setTextColor("#ffffff");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text("Claim_Studio", left, 44);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.text("Workers' Compensation Case Summary", left, 64);
  doc.setFontSize(14);
  doc.setFont("helvetica", "bold");
  doc.text(c.claimNumber, 612 - left, 50, { align: "right" });

  y = 120;

  function sectionTitle(t: string) {
    doc.setFillColor(BLUE);
    doc.rect(left, y - 12, 612 - left * 2, 1.5, "F");
    doc.setTextColor(BLUE);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.text(t, left, y);
    y += 18;
  }
  function field(label: string, value: string) {
    doc.setFont("helvetica", "bold");
    doc.setTextColor(GREY);
    doc.setFontSize(9);
    doc.text(label.toUpperCase(), left, y);
    doc.setFont("helvetica", "normal");
    doc.setTextColor("#1b1f24");
    doc.setFontSize(11);
    const lines = doc.splitTextToSize(value || "—", 612 - left * 2);
    doc.text(lines, left, y + 14);
    y += 14 + lines.length * 13 + 8;
  }
  function twoCol(l1: string, v1: string, l2: string, v2: string) {
    const mid = 306;
    doc.setFont("helvetica", "bold"); doc.setTextColor(GREY); doc.setFontSize(9);
    doc.text(l1.toUpperCase(), left, y);
    doc.text(l2.toUpperCase(), mid, y);
    doc.setFont("helvetica", "normal"); doc.setTextColor("#1b1f24"); doc.setFontSize(11);
    doc.text(v1 || "—", left, y + 14);
    doc.text(v2 || "—", mid, y + 14);
    y += 32;
  }

  sectionTitle("Claim Summary");
  twoCol("Claimant", c.claimant, "Status", c.status);
  twoCol("Severity", c.severity, "Assigned Adjuster", c.adjuster);

  sectionTitle("Incident Details");
  twoCol("Region", c.region, "Department", c.department);
  twoCol("Incident Type", c.incidentType, "Body Part", c.bodyPart);
  twoCol("Date of Injury", c.dateOfInjury, "Date Reported", c.dateReported);
  twoCol("Reserve (USD)", money(c.reserveUsd), "", "");
  field("Incident Description", c.description);

  if (c.classification) {
    sectionTitle("Classification");
    twoCol("Category", c.classification.category, "Severity", c.classification.severity);
    twoCol(
      "Confidence",
      `${Math.round((c.classification.confidence ?? 0) * 100)}%`,
      "Model",
      c.classification.model
    );
    field("Recommended Action", c.classification.recommendedAction);
  }

  doc.setDrawColor("#d9d9d9");
  doc.line(left, 740, 612 - left, 740);
  doc.setTextColor(GREY);
  doc.setFontSize(8);
  doc.text(
    `Generated by Claim_Studio on ${new Date().toLocaleString("en-US")} - WorkersCompensationCase ${c.claimNumber}`,
    left,
    754
  );

  const uri = doc.output("datauristring");
  const base64 = uri.substring(uri.indexOf(",") + 1);
  // Raw bytes for the Dataverse file column (uploadFileToRecord wants binary).
  const bytes = new Uint8Array(doc.output("arraybuffer") as ArrayBuffer);
  return { base64, bytes, fileName: `${c.claimNumber}.pdf` };
}
